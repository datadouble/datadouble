"""The GitLab CI/CD adapter.

``ci init`` writes one file per side of the boundary,
``.gitlab/datadouble-<spec>-<side>.yml``, for the project's ``.gitlab-ci.yml``
to include. It includes the job template (``datadouble.yml`` here) from this
repository at the release's tag, pinned by its SHA-256, and defines a job per
``datadouble`` command line that extends it.

GitLab keeps schedules outside its configuration, so a job runs when the
pipeline's ``DATADOUBLE_JOB`` variable names it (``shop-build``): a pipeline
schedule sets it, as does a person running a pipeline. A job that follows
another (``promote`` after ``build``) runs in the same pipeline and ``needs``
it. On-demand copies belong to a merge request's environment, whose
``on_stop`` job releases them when the request is merged or closed. A
warning exits with 3, which ``allow_failure: exit_codes`` shows as a
warning, and outputs are a dotenv report. The ``lock`` job's new lock and
changes are job artifacts beside it. GitLab masks only variables defined as
masked, so there is no masking at run time.

With a ``git`` spec source, each job's ``before_script`` clones the spec's
repository into the project directory before the template's script runs,
with the host's ``git`` (which the shell executor already clones the
project with). The URL and ref are literals in the script, not variables a
pipeline run could override. The masked variable reaches ``git`` through a
credential helper scoped to the repository's host, which reads it from the
environment, so it is never on a command line or in the clone's
configuration.
"""

import base64
import hashlib
import re
import shlex
from collections.abc import Mapping
from importlib.resources import files
from pathlib import Path, PurePosixPath
from typing import assert_never
from urllib.parse import urlsplit

import yaml
from pydantic import JsonValue

from datadouble.ci import (
    SPEC_CLONE,
    Agent,
    CiError,
    GeneratedFile,
    GitSettings,
    Invocation,
    Job,
    JobKind,
    Pipeline,
    Placeholder,
    Report,
    Trigger,
    credential_name,
)
from datadouble.outcome import ExitCode, Outcome
from datadouble.spec import EnvSecret, NotifyOn

NAME = "gitlab"
TEMPLATE = "datadouble.yml"
TEMPLATE_URL = (
    "https://raw.githubusercontent.com/datadouble/datadouble/v{version}"
    "/ci/gitlab/src/datadouble_gitlab/datadouble.yml"
)
_HOSTED_TAG = re.compile(r"saas-[\w.-]+")
"""GitLab.com's own runners' tags, such as ``saas-linux-small-amd64``."""
_RUN_SOURCES = {
    Trigger.SCHEDULE: ("schedule",),
    Trigger.MANUAL: ("web", "api", "trigger"),
    Trigger.AFTER: ("schedule", "web", "api", "trigger"),
}
_PLACEHOLDERS = {
    Placeholder.RUN: "$CI_PIPELINE_ID",
    Placeholder.OWNER: "mr-$CI_MERGE_REQUEST_IID",
    Placeholder.GENERATION: "$DATADOUBLE_GENERATION",
    Placeholder.DRY_RUN: "$DATADOUBLE_DRY_RUN",
}
_REQUEST = (
    '$CI_PIPELINE_SOURCE == "merge_request_event"'
    " && $CI_MERGE_REQUEST_SOURCE_PROJECT_ID == $CI_PROJECT_ID"
)
"""A merge request from this project: one from a fork never runs on the team's runners."""
_HEADER = """\
# Generated by `datadouble ci init` (Datadouble {version}). Change the spec or
# the options and generate it again, rather than editing it by hand. Include
# it from .gitlab-ci.yml:
#
#   include:
#     - local: {path}
"""


def template() -> bytes:
    """The job template, as published at each release's tag."""
    return files("datadouble_gitlab").joinpath(TEMPLATE).read_bytes()


def integrity() -> str:
    """The template's Subresource Integrity value, for ``include: integrity``."""
    digest = hashlib.sha256(template()).digest()
    return "sha256-" + base64.b64encode(digest).decode()


def _path(pipeline: Pipeline) -> PurePosixPath:
    return PurePosixPath(f".gitlab/datadouble-{pipeline.name}-{pipeline.side}.yml")


def _stem(pipeline: Pipeline, kind: JobKind) -> str:
    """The value of ``DATADOUBLE_JOB`` that runs the job."""
    suffix = f"-{pipeline.side}" if kind is JobKind.PRUNE else ""
    return f"{pipeline.name}-{kind}{suffix}"


def _name(pipeline: Pipeline, job: Job, index: int) -> str:
    base = f"datadouble-{_stem(pipeline, job.kind)}"
    return base if len(job.invocations) == 1 else f"{base}-{index + 1}"


def _environment_name(pipeline: Pipeline) -> str:
    return f"datadouble/{pipeline.name}/mr-$CI_MERGE_REQUEST_IID"


def _tags(pipeline: Pipeline) -> list[JsonValue]:
    tags = [tag.strip() for tag in (pipeline.runner or "").split(",") if tag.strip()]
    hosted = [tag for tag in tags if _HOSTED_TAG.fullmatch(tag)]
    if hosted:
        message = (
            f"{', '.join(hosted)} selects GitLab's hosted runners; Datadouble's jobs need runners"
            " that keep their files, and build, promote and lock need runners inside the"
            " production boundary (decision 19)"
        )
        raise CiError(message)
    if not tags:
        message = "name the runner tags the jobs run on (--runner)"
        raise CiError(message)
    return list[JsonValue](tags)


def _lines(values: tuple[str, ...]) -> str:
    return "".join(f"{value}\n" for value in values)


def _argument(argument: str | Placeholder) -> str:
    return _PLACEHOLDERS[argument] if isinstance(argument, Placeholder) else argument


def _rules(pipeline: Pipeline, job: Job, invocation: Invocation) -> list[JsonValue]:
    triggers = invocation.when or job.triggers
    rules: list[JsonValue] = []
    own = (Trigger.SCHEDULE, Trigger.MANUAL)
    sources = sorted({source for t in triggers if t in own for source in _RUN_SOURCES[t]})
    if sources:
        chosen = f'$DATADOUBLE_JOB == "{_stem(pipeline, job.kind)}"'
        pattern = "|".join(sources)
        rules.append({"if": f"{chosen} && $CI_PIPELINE_SOURCE =~ /^({pattern})$/"})
    if job.after is not None and Trigger.AFTER in triggers:
        after = f'$DATADOUBLE_JOB == "{_stem(pipeline, job.after)}"'
        pattern = "|".join(_RUN_SOURCES[Trigger.AFTER])
        rules.append({"if": f"{after} && $CI_PIPELINE_SOURCE =~ /^({pattern})$/"})
    if Trigger.REQUEST_OPENED in triggers:
        rules.append({"if": _REQUEST})
    if Trigger.REQUEST_CLOSED in triggers:
        rules.append({"if": _REQUEST, "when": "manual", "allow_failure": True})
    return rules


_CLONE_USER = "oauth2"
"""The user name a clone gives with a token when the URL names none: GitLab accepts any
with a personal, project or group access token."""
_USER = re.compile(r"[A-Za-z0-9._-]+")


def _clone_script(git: GitSettings) -> list[JsonValue]:
    """``before_script`` lines that clone a ``git`` spec source into the project directory.

    The URL and ref are written into the script, quoted, rather than read from
    variables a pipeline run could override, and ``--`` ends git's options
    before them. The credential helper answers only for the spec repository's
    host, and prints the token only when ``git`` asks for it, reading the
    masked variable from the environment: the log shows the line as written
    here, and the token never reaches a command line or the clone's
    configuration. Fetching the one ref works for a branch, a tag
    (``refs/tags/<tag>``) or a full commit SHA.
    """
    url = urlsplit(git.url)
    if url.scheme != "https" or not url.hostname:
        message = f"GitLab jobs clone the spec over https with a token; {git.url} is not https"
        raise CiError(message)
    user = url.username or _CLONE_USER
    if not _USER.fullmatch(user):
        message = f"the user name in {git.url} must be letters, digits, `.`, `_` and `-`"
        raise CiError(message)
    credential = credential_name(git, NAME)
    host = f"https://{url.netloc.rpartition('@')[2]}"
    helper = (
        f"credential.{host}.helper="
        f'!f() {{ if [ "$1" = get ]; then echo username={user};'
        f' echo "password=${credential}"; fi; }}; f'
    )
    fetch = (
        f"git -C {SPEC_CLONE} -c credential.helper= -c {shlex.quote(helper)}"
        f" fetch --quiet --depth 1 -- {shlex.quote(git.url)} {shlex.quote(git.ref)}"
    )
    lines = (
        "set -euo pipefail",
        f"rm -rf {SPEC_CLONE}",
        f"git init --quiet {SPEC_CLONE}",
        fetch,
        f"git -C {SPEC_CLONE} checkout --quiet FETCH_HEAD",
    )
    return [_lines(lines)]


def _clone(pipeline: Pipeline) -> dict[str, JsonValue]:
    """A job's ``before_script`` for a ``git`` spec source; nothing for the others.

    It goes in the generated job, not the template, which is pinned by its SHA-256.
    It replaces a ``before_script`` the project sets in ``default``.
    """
    git = pipeline.git()
    return {} if git is None else {"before_script": _clone_script(git)}


def _job(pipeline: Pipeline, job: Job, index: int, stop: str | None) -> dict[str, JsonValue]:
    invocation = job.invocations[index]
    triggers = invocation.when or job.triggers
    body: dict[str, JsonValue] = {
        "extends": ".datadouble",
        "tags": _tags(pipeline),
        "resource_group": f"datadouble-{_stem(pipeline, job.kind)}",
        "timeout": f"{job.timeout_minutes}m",
        "rules": _rules(pipeline, job, invocation),
    }
    if job.after is not None and Trigger.AFTER in triggers:
        after = next(j for j in pipeline.jobs if j.kind is job.after)
        body["needs"] = [
            {"job": _name(pipeline, after, i), "optional": True}
            for i in range(len(after.invocations))
        ]
    if Trigger.REQUEST_OPENED in triggers:
        environment: dict[str, JsonValue] = {"name": _environment_name(pipeline)}
        if stop is not None:
            environment["on_stop"] = stop
        body["environment"] = environment
    if Trigger.REQUEST_CLOSED in triggers:
        body["environment"] = {"name": _environment_name(pipeline), "action": "stop"}
    variables: dict[str, JsonValue] = {
        "DATADOUBLE_CI_JOB": str(job.kind),
        "DATADOUBLE_IMAGE": pipeline.image,
        "DATADOUBLE_USER": pipeline.user,
    }
    if pipeline.docker is not None:
        variables["DATADOUBLE_DOCKER"] = pipeline.docker
    if pipeline.docker_socket is not None:
        variables["DATADOUBLE_DOCKER_SOCKET"] = pipeline.docker_socket
    if job.mounts:
        variables["DATADOUBLE_MOUNTS"] = _lines(job.mounts)
    if job.environment:
        variables["DATADOUBLE_ENVIRONMENT"] = _lines(job.environment)
    if job.artifacts is not None:
        variables["DATADOUBLE_ARTIFACTS"] = job.artifacts
        # Paths replace the template's list, so the outputs file stays in it.
        body["artifacts"] = {"paths": ["datadouble.env", f"{job.artifacts}/"]}
    variables["DATADOUBLE_ARGUMENTS"] = _lines(tuple(_argument(a) for a in invocation.arguments))
    body["variables"] = variables
    return body | _clone(pipeline)


def _webhook_variables(pipeline: Pipeline) -> tuple[str, ...]:
    """The environment variables the spec's webhooks read their URLs from."""
    hooks = pipeline.notify.webhooks() if pipeline.notify is not None else ()
    return tuple(sorted({h.url.env for h in hooks if isinstance(h.url, EnvSecret)}))


def _stop_job(pipeline: Pipeline) -> str | None:
    """The job that releases a merge request's copies, if the pipeline has one."""
    for job in pipeline.jobs:
        for index, invocation in enumerate(job.invocations):
            if Trigger.REQUEST_CLOSED in invocation.when:
                return _name(pipeline, job, index)
    return None


def _variables(pipeline: Pipeline) -> dict[str, JsonValue]:
    """The pipeline variables a person running a pipeline fills in."""
    names = ", ".join(_stem(pipeline, job.kind) for job in pipeline.jobs)
    variables: dict[str, JsonValue] = {
        "DATADOUBLE_JOB": {"value": "", "description": f"The Datadouble job to run: {names}"}
    }
    parameters = {p for job in pipeline.jobs for p in job.parameters}
    if Placeholder.GENERATION in parameters:
        variables["DATADOUBLE_GENERATION"] = {
            "value": "",
            "description": "The staged generation to activate",
        }
    if Placeholder.DRY_RUN in parameters:
        variables["DATADOUBLE_DRY_RUN"] = {
            "value": "",
            "options": ["", "--dry-run"],
            "description": "--dry-run reports what prune would remove, without removing it",
        }
    return variables


def configuration(pipeline: Pipeline) -> dict[str, JsonValue]:
    """The included file's content, before it is written as YAML."""
    remote = TEMPLATE_URL.format(version=pipeline.version)
    config: dict[str, JsonValue] = {
        "include": [{"remote": remote, "integrity": integrity()}],
        "variables": _variables(pipeline),
    }
    stop = _stop_job(pipeline)
    for job in pipeline.jobs:
        for index in range(len(job.invocations)):
            config[_name(pipeline, job, index)] = _job(pipeline, job, index, stop)
    return config


class _Dumper(yaml.SafeDumper):
    """Block style for multi-line strings."""


def _string(_dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    style = "|" if "\n" in value else None
    return yaml.ScalarNode("tag:yaml.org,2002:str", value, style=style)


_Dumper.add_representer(str, _string)


def render(pipeline: Pipeline) -> str:
    """The included file."""
    body = yaml.dump(configuration(pipeline), Dumper=_Dumper, sort_keys=False, width=100)
    return _HEADER.format(version=pipeline.version, path=_path(pipeline)) + body


class GitLab:
    """GitLab CI: an included file of jobs, dotenv outputs and exit codes."""

    @property
    def name(self) -> str:
        """``gitlab``."""
        return NAME

    @property
    def agents(self) -> tuple[Agent, ...]:
        """Runners with Docker."""
        return (Agent.DOCKER,)

    def generate(self, pipeline: Pipeline) -> tuple[GeneratedFile, ...]:
        """One file of jobs for the side of the boundary."""
        return (GeneratedFile(path=_path(pipeline), content=render(pipeline)),)

    def instructions(self, pipeline: Pipeline) -> tuple[str, ...]:
        """Including the file, pipeline schedules and merge request pipelines."""
        steps = [f"include {_path(pipeline)} from .gitlab-ci.yml (include: local)"]
        steps.extend(
            f"create a pipeline schedule `{job.schedule}` in the UTC time zone, with the"
            f" variable DATADOUBLE_JOB={_stem(pipeline, job.kind)}"
            for job in pipeline.jobs
            if job.schedule is not None
        )
        requests = {Trigger.REQUEST_OPENED, Trigger.REQUEST_CLOSED}
        if any(requests & set(job.triggers) for job in pipeline.jobs):
            steps.append(
                "run merge request pipelines (workflow:rules), which make and release"
                " on-demand copies"
            )
        if pipeline.environment():
            steps.append("define each variable above as a masked, protected CI/CD variable")
        hooks = _webhook_variables(pipeline)
        if hooks and any(requests & set(job.triggers) for job in pipeline.jobs):
            steps.append(
                f"on-demand provision and release run in merge request pipelines, which see no"
                f" protected variables: make {', '.join(hooks)} available there (not protected,"
                " or scoped to the environments those jobs use), or their webhook is not posted"
            )
        git = pipeline.git()
        if git is not None and any(requests & set(job.triggers) for job in pipeline.jobs):
            steps.append(
                f"on-demand provision and release run in merge request pipelines, which see no"
                f" protected variables: make {git.credential} available there (not protected,"
                " or scoped to the environments those jobs use), or they cannot clone the spec"
            )
        emails = pipeline.notify.emails() if pipeline.notify is not None else ()
        if pipeline.notify is not None and emails:
            step = (
                f"for notify's email, turn on the project's Pipeline status emails integration"
                f" (Settings > Integrations) for {', '.join(emails)}, notifying only broken"
                " pipelines"
            )
            if NotifyOn.WARNING in pipeline.notify.when:
                step += (
                    "; GitLab mails failed pipelines only, so a warning, a job allowed to fail,"
                    " mails nobody: list a webhook to hear about warnings"
                )
            if NotifyOn.RECOVERY in pipeline.notify.when:
                step += (
                    "; that integration never mails a recovery, so for recovery mail turn on"
                    " the Fixed pipeline event in the notification settings (Custom level) of"
                    " whoever owns the pipeline schedules, since GitLab mails a fixed pipeline"
                    " only to its author, or list a webhook whose service mails those addresses"
                )
            steps.append(step)
        return tuple(steps)

    def vendor_hosted(self, environ: Mapping[str, str]) -> str | None:
        """GitLab.com's hosted runners carry ``saas-`` tags."""
        tags = re.findall(r"[\w.-]+", environ.get("CI_RUNNER_TAGS", ""))
        hosted = [tag for tag in tags if _HOSTED_TAG.fullmatch(tag)]
        return f"a GitLab-hosted runner ({hosted[0]})" if hosted else None

    def run_url(self, environ: Mapping[str, str]) -> str | None:
        """The job's page, ``CI_JOB_URL``."""
        return environ.get("CI_JOB_URL") or None

    def mask(self, value: str) -> None:
        """GitLab masks only variables defined as masked; nothing to do at run time."""
        del value

    def report(self, report: Report, directory: Path | None) -> ExitCode:
        """Outputs as a dotenv report; a warning exits with 3."""
        if directory is not None:
            lines = (
                f"DATADOUBLE_{name.upper()}={value}\n"
                for name, value in report.outputs.items()
                if "\n" not in value
            )
            (directory / "outputs").write_text("".join(lines), encoding="utf-8")
        match report.outcome:
            case Outcome.SUCCESS:
                return ExitCode.SUCCESS
            case Outcome.WARNING:
                return ExitCode.WARNING
            case Outcome.FAILURE:
                return ExitCode.FAILURE
            case _:
                assert_never(report.outcome)


def adapter() -> GitLab:
    """The ``gitlab`` entry point."""
    return GitLab()

"""The GitHub Actions CI/CD adapter.

Generated workflows run each ``datadouble`` command through this
repository's action (``ci/github-actions``), which runs the pinned Datadouble
image as the engine's user, with the runner's Docker daemon and the paths
the spec names. At run time the adapter writes step outputs and the job
summary into a directory the action hands on to ``GITHUB_OUTPUT`` and
``GITHUB_STEP_SUMMARY``, prints warning and error annotations, and masks
resolved secrets with ``add-mask``. A warning is a warning annotation on a
passing step, since GitHub Actions has no unstable state.
"""

import os
import re
import secrets
import sys
from collections.abc import Mapping
from pathlib import Path, PurePosixPath
from typing import TextIO, override

import yaml
from pydantic import JsonValue

from datadouble.ci import (
    CiError,
    GeneratedFile,
    Invocation,
    Job,
    JobKind,
    Pipeline,
    Placeholder,
    Report,
    Trigger,
)
from datadouble.outcome import ExitCode, Outcome

NAME = "github-actions"
ACTION = "datadouble/datadouble/ci/github-actions"
"""The action generated workflows use, at the release tag of the Datadouble that wrote them."""
CHECKOUT = "actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1"
CHECKOUT_VERSION = "v7.0.1"
_HOSTED_LABEL = re.compile(r"(ubuntu|windows|macos)-[\w.-]+")
"""GitHub's own runner labels, such as ``ubuntu-latest``."""
_EVENTS = {
    Trigger.SCHEDULE: "schedule",
    Trigger.AFTER: "workflow_run",
    Trigger.REQUEST_OPENED: "pull_request",
    Trigger.REQUEST_CLOSED: "pull_request",
    Trigger.MANUAL: "workflow_dispatch",
}
_PLACEHOLDERS = {
    Placeholder.RUN: "${{ github.run_id }}",
    Placeholder.OWNER: "pr-${{ github.event.pull_request.number }}",
    Placeholder.GENERATION: "${{ inputs.generation }}",
    Placeholder.DRY_RUN: "${{ inputs.dry-run && '--dry-run' || '' }}",
}
_PARAMETERS: dict[Placeholder, dict[str, JsonValue]] = {
    Placeholder.GENERATION: {
        "description": "The staged generation to activate",
        "required": True,
        "type": "string",
    },
    Placeholder.DRY_RUN: {
        "description": "Report what would be removed, without removing it",
        "required": False,
        "type": "boolean",
        "default": False,
    },
}
_HEADER = """\
# Generated by `datadouble ci init` (Datadouble {version}). Change the spec or
# the options and generate it again, rather than editing it by hand.
"""


def _escape(text: str) -> str:
    """Escape a workflow command's message, as the runner expects."""
    return text.replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")


def _stem(pipeline: Pipeline, kind: JobKind) -> str:
    """The job's name within the spec; prune runs on both sides, so it says which."""
    return f"{kind}-{pipeline.side}" if kind is JobKind.PRUNE else str(kind)


def _workflow_name(pipeline: Pipeline, kind: JobKind) -> str:
    return f"Datadouble {pipeline.name} {_stem(pipeline, kind)}"


def _argument(argument: str | Placeholder) -> str:
    return _PLACEHOLDERS[argument] if isinstance(argument, Placeholder) else argument


def _lines(values: tuple[str, ...]) -> str:
    return "".join(f"{value}\n" for value in values)


def _runs_on(pipeline: Pipeline) -> JsonValue:
    """``self-hosted`` and the runner's labels: jobs never run on GitHub's own runners."""
    named = [label.strip() for label in (pipeline.runner or "").split(",") if label.strip()]
    hosted = [label for label in named if _HOSTED_LABEL.fullmatch(label)]
    if hosted:
        message = (
            f"{', '.join(hosted)} is a GitHub-hosted runner; Datadouble's jobs need runners"
            " that keep their files, and build and promote need runners inside the"
            " production boundary (decision 19)"
        )
        raise CiError(message)
    labels = ["self-hosted", *(label for label in named if label != "self-hosted")]
    return labels[0] if len(labels) == 1 else list[JsonValue](labels)


def _on(pipeline: Pipeline, job: Job) -> dict[str, JsonValue]:
    on: dict[str, JsonValue] = {}
    if job.schedule is not None:
        on["schedule"] = [{"cron": job.schedule}]
    if job.after is not None:
        on["workflow_run"] = {
            "workflows": [_workflow_name(pipeline, job.after)],
            "types": ["completed"],
        }
    opened = Trigger.REQUEST_OPENED in job.triggers
    closed = Trigger.REQUEST_CLOSED in job.triggers
    if opened or closed:
        on["pull_request"] = {"types": ["opened", "reopened"] if opened else ["closed"]}
    if Trigger.MANUAL in job.triggers:
        inputs = {str(name): _PARAMETERS[name] for name in job.parameters}
        on["workflow_dispatch"] = {"inputs": dict[str, JsonValue](inputs)} if inputs else None
    return on


def _condition(job: Job) -> str | None:
    conditions: list[str] = []
    if job.after is not None:
        conditions.append(
            "(github.event_name != 'workflow_run'"
            " || github.event.workflow_run.conclusion == 'success')"
        )
    if Trigger.REQUEST_OPENED in job.triggers or Trigger.REQUEST_CLOSED in job.triggers:
        # A fork's pull request must never run on the team's own runners.
        conditions.append(
            "(github.event_name != 'pull_request'"
            " || github.event.pull_request.head.repo.full_name == github.repository)"
        )
    return " && ".join(conditions) or None


def _step(pipeline: Pipeline, job: Job, invocation: Invocation) -> dict[str, JsonValue]:
    step: dict[str, JsonValue] = {"name": f"datadouble {invocation.arguments[0]}"}
    if invocation.when:
        events = sorted({_EVENTS[trigger] for trigger in invocation.when})
        step["if"] = " || ".join(f"github.event_name == '{event}'" for event in events)
    step["uses"] = f"{ACTION}@v{pipeline.version}"
    if job.environment:
        step["env"] = {name: f"${{{{ secrets.{name} }}}}" for name in job.environment}
    inputs: dict[str, JsonValue] = {"image": pipeline.image, "user": pipeline.user}
    if job.mounts:
        inputs["mounts"] = _lines(job.mounts)
    if job.environment:
        inputs["environment"] = _lines(job.environment)
    inputs["arguments"] = _lines(tuple(_argument(a) for a in invocation.arguments))
    step["with"] = inputs
    return step


def _group(pipeline: Pipeline, job: Job) -> str:
    group = f"datadouble-{pipeline.name}-{_stem(pipeline, job.kind)}"
    if Trigger.REQUEST_OPENED in job.triggers or Trigger.REQUEST_CLOSED in job.triggers:
        return group + "-${{ github.event.pull_request.number || 'scheduled' }}"
    return group


def _workflow(pipeline: Pipeline, job: Job) -> dict[str, JsonValue]:
    permissions: dict[str, JsonValue] = {"contents": "read"}
    if job.kind is JobKind.BUILD and pipeline.identity_token:
        permissions["id-token"] = "write"
    body: dict[str, JsonValue] = {"name": str(job.kind), "runs-on": _runs_on(pipeline)}
    condition = _condition(job)
    if condition is not None:
        body["if"] = condition
    body["timeout-minutes"] = job.timeout_minutes
    checkout: dict[str, JsonValue] = {"uses": CHECKOUT, "with": {"persist-credentials": False}}
    steps: list[JsonValue] = [checkout]
    steps.extend(_step(pipeline, job, invocation) for invocation in job.invocations)
    body["steps"] = steps
    return {
        "name": _workflow_name(pipeline, job.kind),
        "on": _on(pipeline, job),
        "permissions": permissions,
        "concurrency": {"group": _group(pipeline, job), "cancel-in-progress": False},
        "jobs": {str(job.kind): body},
    }


class _Dumper(yaml.SafeDumper):
    """Block style for lists and multi-line strings, indented as GitHub's examples are."""

    @override
    def increase_indent(self, flow: bool = False, indentless: bool = False) -> None:
        """Indent list items under their key."""
        super().increase_indent(flow=flow, indentless=False)


def _string(_dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    style = "|" if "\n" in value else None
    return yaml.ScalarNode("tag:yaml.org,2002:str", value, style=style)


_Dumper.add_representer(str, _string)


def render(pipeline: Pipeline, job: Job) -> str:
    """One job's workflow file."""
    text = yaml.dump(_workflow(pipeline, job), Dumper=_Dumper, sort_keys=False, width=100)
    # PyYAML quotes `on`, a boolean in YAML 1.1; GitHub reads either form.
    text = text.replace("'on':", "on:", 1).replace("workflow_dispatch: null", "workflow_dispatch:")
    text = text.replace(f"uses: {CHECKOUT}\n", f"uses: {CHECKOUT} # {CHECKOUT_VERSION}\n")
    # The job a workflow_run follows is never started by a pull request, and the
    # follower checks out the default branch without credentials.
    text = text.replace(
        "  workflow_run:\n", "  workflow_run: # zizmor: ignore[dangerous-triggers]\n", 1
    )
    return _HEADER.format(version=pipeline.version) + text


class GitHubActions:
    """GitHub Actions: workflows, step outputs, the job summary and annotations."""

    def __init__(self, environ: Mapping[str, str], stream: TextIO) -> None:
        """Report with ``environ``'s files; print workflow commands to ``stream``."""
        self.environ = environ
        self.stream = stream

    @property
    def name(self) -> str:
        """``github-actions``."""
        return NAME

    def generate(self, pipeline: Pipeline) -> tuple[GeneratedFile, ...]:
        """A workflow per job under ``.github/workflows``."""
        return tuple(
            GeneratedFile(
                path=PurePosixPath(
                    f".github/workflows/datadouble-{pipeline.name}-{_stem(pipeline, job.kind)}.yml"
                ),
                content=render(pipeline, job),
            )
            for job in pipeline.jobs
        )

    def instructions(self, pipeline: Pipeline) -> tuple[str, ...]:
        """Workflows hold everything, schedules included."""
        del pipeline
        return ()

    def vendor_hosted(self, environ: Mapping[str, str]) -> str | None:
        """GitHub's runners say ``RUNNER_ENVIRONMENT=github-hosted``."""
        if environ.get("RUNNER_ENVIRONMENT") == "github-hosted":
            return "a GitHub-hosted runner"
        return None

    def mask(self, value: str) -> None:
        """``add-mask`` for each line of the value."""
        for line in value.splitlines():
            if line.strip():
                self.stream.write(f"::add-mask::{line}\n")
        self.stream.flush()

    def report(self, report: Report, directory: Path | None) -> ExitCode:
        """Outputs and the summary, to ``directory`` or the runner's files; then annotations."""
        outputs_path, summary_path = self._paths(directory)
        if outputs_path is not None:
            with outputs_path.open("a", encoding="utf-8") as handle:
                for name, value in report.outputs.items():
                    delimiter = f"datadouble_{secrets.token_hex(8)}"
                    handle.write(f"{name}<<{delimiter}\n{value}\n{delimiter}\n")
        if summary_path is not None:
            with summary_path.open("a", encoding="utf-8") as handle:
                handle.write(f"### Datadouble {report.command}: {report.outcome}\n\n")
                handle.write(f"```text\n{report.summary}\n```\n")
        for warning in report.warnings:
            self.stream.write(f"::warning title=Datadouble::{_escape(warning)}\n")
        if report.message is not None:
            self.stream.write(f"::error title=Datadouble::{_escape(report.message)}\n")
        self.stream.flush()
        return ExitCode.FAILURE if report.outcome is Outcome.FAILURE else ExitCode.SUCCESS

    def _paths(self, directory: Path | None) -> tuple[Path | None, Path | None]:
        if directory is not None:
            return directory / "outputs", directory / "summary.md"
        outputs = self.environ.get("GITHUB_OUTPUT")
        summary = self.environ.get("GITHUB_STEP_SUMMARY")
        return (Path(outputs) if outputs else None, Path(summary) if summary else None)


def adapter() -> GitHubActions:
    """The ``github-actions`` entry point."""
    return GitHubActions(os.environ, sys.stderr)

"""The Argo CD CI/CD adapter.

``ci init`` writes an Argo CD Application per side of the boundary,
``argocd/datadouble-<spec>-<side>.yaml``, which installs this repository's
Helm chart (``ci/kubernetes/chart``) at the release's tag with the jobs as
values, the spec and its catalog lock among them. Each job is a CronJob,
suspended when it has no schedule, so it runs by hand with ``kubectl create
job --from``; a job that follows another (``promote`` after ``build``) also
runs as a later step of that job's pod. On-demand copies are Argo CD hooks:
an Application whose ``owner`` value names a request (one an ApplicationSet
makes per pull request) makes the request's copies before it syncs and
releases them when it is deleted.

Pods run the Datadouble image itself, as the engine's user, with every path
the spec names on one PersistentVolumeClaim, mounted at the same path, as
the ``kubernetes`` runtime needs. A Job has no warning state, so a warning
succeeds and says so in the log; the outputs are the container's
termination message. Kubernetes keeps no job artifacts, so the ``lock``
job writes its new lock and changes into an ``emptyDir`` and prints both to
the job's log.

The spec's ``notify`` webhooks Datadouble posts itself, from each step; a
Job has no page, so their ``run_url`` is null. Kubernetes has no mail, so
``notify`` email fails ``ci init``, by name.
"""

import sys
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import TextIO, assert_never

import yaml
from pydantic import JsonValue

from datadouble.ci import (
    CLAIM,
    Agent,
    CiError,
    GeneratedFile,
    Invocation,
    Job,
    JobKind,
    Pipeline,
    Placeholder,
    Report,
    Side,
    Trigger,
    claim_mount,
    runtime_namespace,
)
from datadouble.outcome import ExitCode, Outcome

NAME = "argocd"
REPOSITORY = "https://github.com/datadouble/datadouble.git"
CHART = "ci/kubernetes/chart"
TERMINATION_LOG = Path("/dev/termination-log")
_PLACEHOLDERS = {
    Placeholder.RUN: "$(DATADOUBLE_RUN)",
    Placeholder.OWNER: "$(DATADOUBLE_OWNER)",
    Placeholder.GENERATION: "$(DATADOUBLE_GENERATION)",
    Placeholder.DRY_RUN: "$(DATADOUBLE_DRY_RUN)",
}
_HOOKS = {Trigger.REQUEST_OPENED: "PreSync", Trigger.REQUEST_CLOSED: "PostDelete"}
_HEADER = """\
# Generated by `datadouble ci init` (Datadouble {version}). Change the spec or
# the options and generate it again, rather than editing it by hand: the spec
# and its catalog lock are copied into the values below.
"""


def _release(pipeline: Pipeline) -> str:
    return f"{pipeline.name}-{pipeline.side}"


def _path(pipeline: Pipeline) -> PurePosixPath:
    return PurePosixPath(f"argocd/datadouble-{_release(pipeline)}.yaml")


def _namespace(pipeline: Pipeline) -> str:
    if pipeline.cloud:
        message = "Argo CD installs into its own cluster; a cloud is for Jenkins' Kubernetes agents"
        raise CiError(message)
    if not pipeline.runner:
        message = "name the Kubernetes namespace the jobs run in (--runner)"
        raise CiError(message)
    runtime_namespace(pipeline, pipeline.runner)
    return pipeline.runner


def _mount(pipeline: Pipeline) -> str:
    """The directory every path the spec names is under: the claim's mount."""
    return claim_mount(pipeline)


def _step(job: Job, invocation: Invocation) -> dict[str, JsonValue]:
    arguments: list[JsonValue] = [
        _PLACEHOLDERS[a] if isinstance(a, Placeholder) else a for a in invocation.arguments
    ]
    return {
        "job": str(job.kind),
        "arguments": arguments,
        "environment": list[JsonValue](job.environment),
    }


def _stem(pipeline: Pipeline, kind: JobKind) -> str:
    return f"{kind}-{pipeline.side}" if kind is JobKind.PRUNE else str(kind)


@dataclass
class _Entry:
    """One of the chart's jobs: a CronJob, or a request's hook."""

    name: str
    minutes: int
    steps: list[JsonValue]
    schedule: str = ""
    hook: str | None = None
    artifacts: str | None = None

    def value(self) -> dict[str, JsonValue]:
        entry: dict[str, JsonValue] = {"name": self.name}
        if self.hook is not None:
            entry["hook"] = self.hook
        else:
            entry["schedule"] = self.schedule
        entry["timeoutMinutes"] = self.minutes
        if self.artifacts is not None:
            entry["artifacts"] = self.artifacts
        entry["steps"] = self.steps
        return entry


def _jobs(pipeline: Pipeline) -> list[JsonValue]:
    """The chart's jobs: CronJobs, with followers as later steps, and request hooks."""
    entries: dict[str, _Entry] = {}
    hooks: list[_Entry] = []
    for job in pipeline.jobs:
        steps: list[JsonValue] = []
        for invocation in job.invocations:
            hook = next((_HOOKS[t] for t in invocation.when or job.triggers if t in _HOOKS), None)
            if hook is None:
                steps.append(_step(job, invocation))
            else:
                name = "request-copies" if hook == "PreSync" else "request-release"
                hooks.append(_Entry(name, job.timeout_minutes, [_step(job, invocation)], hook=hook))
        if steps:
            stem = _stem(pipeline, job.kind)
            entries[stem] = _Entry(
                stem,
                job.timeout_minutes,
                steps,
                schedule=job.schedule or "",
                artifacts=job.artifacts,
            )
    for job in pipeline.jobs:
        leader = entries.get(_stem(pipeline, job.after)) if job.after is not None else None
        follower = entries.get(_stem(pipeline, job.kind))
        if leader is not None and follower is not None and Trigger.AFTER in job.triggers:
            leader.steps = [*leader.steps, *follower.steps]
            leader.minutes += follower.minutes
    return [entry.value() for entry in (*entries.values(), *hooks)]


def values(pipeline: Pipeline) -> dict[str, JsonValue]:
    """The chart's values for one side's jobs."""
    uid, _, gid = pipeline.user.partition(":")
    secret = f"datadouble-{pipeline.name}" if pipeline.environment() else ""
    return {
        "name": f"datadouble-{_release(pipeline)}",
        "image": pipeline.image,
        "user": {"uid": int(uid), "gid": int(gid)},
        "spec": {"path": pipeline.spec, "content": pipeline.spec_text, "lock": pipeline.lock_text},
        "claim": {"name": CLAIM, "mount": _mount(pipeline)},
        "secret": secret,
        "persistentVolumes": pipeline.side is Side.NON_PRODUCTION,
        "jobs": _jobs(pipeline),
    }


def application(pipeline: Pipeline) -> dict[str, JsonValue]:
    """The Argo CD Application that installs the chart with the side's values."""
    return {
        "apiVersion": "argoproj.io/v1alpha1",
        "kind": "Application",
        "metadata": {"name": f"datadouble-{_release(pipeline)}", "namespace": "argocd"},
        "spec": {
            "project": "default",
            "destination": {
                "server": "https://kubernetes.default.svc",
                "namespace": _namespace(pipeline),
            },
            "source": {
                "repoURL": REPOSITORY,
                "targetRevision": f"v{pipeline.version}",
                "path": CHART,
                "helm": {"releaseName": _release(pipeline), "valuesObject": values(pipeline)},
            },
            "syncPolicy": {"automated": {"prune": True, "selfHeal": True}},
        },
    }


class _Dumper(yaml.SafeDumper):
    """Block style for multi-line strings, such as the spec."""


def _string(_dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    style = "|" if "\n" in value else None
    return yaml.ScalarNode("tag:yaml.org,2002:str", value, style=style)


_Dumper.add_representer(str, _string)


def render(pipeline: Pipeline) -> str:
    """The Application manifest."""
    body = yaml.dump(application(pipeline), Dumper=_Dumper, sort_keys=False, width=100)
    return _HEADER.format(version=pipeline.version) + body


class ArgoCd:
    """Argo CD: an Application of this repository's chart; Jobs' own state."""

    def __init__(
        self, termination_log: Path = TERMINATION_LOG, stream: TextIO | None = None
    ) -> None:
        """Write outputs to ``termination_log`` when there is no directory for them.

        Files a job publishes are printed to ``stream``, the job's log (standard output).
        """
        self.termination_log = termination_log
        self.stream = stream

    @property
    def name(self) -> str:
        """``argocd``."""
        return NAME

    @property
    def agents(self) -> tuple[Agent, ...]:
        """Pods of the Datadouble image."""
        return (Agent.KUBERNETES,)

    def generate(self, pipeline: Pipeline) -> tuple[GeneratedFile, ...]:
        """One Application per side of the boundary; refuses notify's email and Docker."""
        if pipeline.notify is not None and pipeline.notify.emails():
            message = (
                "argocd cannot send notify's email: Kubernetes Jobs have no mail mechanism;"
                " list a webhook instead, whose service can mail people"
            )
            raise CiError(message)
        if pipeline.docker is not None or pipeline.docker_socket is not None:
            message = (
                "Argo CD's jobs are pods that run the Datadouble image themselves, without"
                " Docker; leave out the Docker command and socket"
            )
            raise CiError(message)
        return (GeneratedFile(path=_path(pipeline), content=render(pipeline)),)

    def instructions(self, pipeline: Pipeline) -> tuple[str, ...]:
        """The namespace's claim, Secret and boundary mark, and how jobs start."""
        namespace = _namespace(pipeline)
        steps = [
            (
                f"in the namespace {namespace}, create the PersistentVolumeClaim {CLAIM},"
                f" holding {_mount(pipeline)}, owned by {pipeline.user}"
            ),
            f"add {_path(pipeline)} to Argo CD (kubectl apply -n argocd -f ...)",
        ]
        if pipeline.environment():
            steps.append(
                f"create the Secret datadouble-{pipeline.name} in {namespace}, with each"
                " variable above as a key"
            )
        if pipeline.side is Side.PRODUCTION:
            steps.append(
                f"inside the production boundary only, create the ConfigMap"
                f" datadouble-boundary in {namespace} with DATADOUBLE_BOUNDARY=inside"
            )
        steps.append(
            f"run a job by hand with kubectl -n {namespace} create job"
            f" --from=cronjob/datadouble-{_release(pipeline)}-<job> <name>"
        )
        requests = {Trigger.REQUEST_OPENED, Trigger.REQUEST_CLOSED}
        if any(requests & set(job.triggers) for job in pipeline.jobs):
            steps.append(
                "for on-demand copies, make an ApplicationSet with your source host's pull"
                " request generator whose template is this Application, with a name per"
                " request and helm.valuesObject.owner set to pr-<number>"
            )
        if pipeline.notify is not None:
            steps.append(
                f"Datadouble posts notify's webhooks itself, so a Job that fails before it"
                f" starts (an image that cannot be pulled, a missing claim or Secret, a pod"
                f" stopped at its deadline) posts nothing: alert on failed Jobs in {namespace}"
                " with your cluster's monitoring, such as kube-state-metrics'"
                " kube_job_status_failed"
            )
        return tuple(steps)

    def vendor_hosted(self, environ: Mapping[str, str]) -> str | None:
        """Clusters are always the team's own."""
        del environ
        return None

    def run_url(self, environ: Mapping[str, str]) -> str | None:
        """A Job has no web page of its own."""
        del environ
        return None

    def mask(self, value: str) -> None:
        """Pods' logs have no masking; secrets never reach them."""
        del value

    def report(self, report: Report, directory: Path | None) -> ExitCode:
        """Outputs as the termination message, files in the log; a warning succeeds."""
        stream = sys.stdout if self.stream is None else self.stream
        for path in report.files:
            stream.write(f"==> {path} <==\n{path.read_text(encoding='utf-8')}")
        stream.flush()
        lines = "".join(
            f"{name}={value}\n" for name, value in report.outputs.items() if "\n" not in value
        )
        target = directory / "outputs" if directory is not None else self.termination_log
        if directory is not None or target.exists():
            target.write_text(lines, encoding="utf-8")
        match report.outcome:
            case Outcome.SUCCESS | Outcome.WARNING:
                return ExitCode.SUCCESS
            case Outcome.FAILURE:
                return ExitCode.FAILURE
            case _:
                assert_never(report.outcome)


def adapter() -> ArgoCd:
    """The ``argocd`` entry point."""
    return ArgoCd()

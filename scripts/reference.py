"""Write, or check, the generated reference pages of the documentation site.

docs/using/spec-reference.md comes from the spec's JSON Schema, and
docs/using/cli-reference.md from the command-line parser, so neither can
drift from the code. The CLI page is built from the parser's arguments rather
than its help text, whose layout changes between Python releases.

    uv run python scripts/reference.py write
    uv run python scripts/reference.py check   # fails if the pages are stale
"""

import json
import sys
from collections.abc import Iterator, Mapping, Sequence
from pathlib import Path

from pydantic import JsonValue, TypeAdapter

from datadouble.cli import CommandParser, build_parser
from datadouble.spec import spec_schema

ROOT = Path(__file__).resolve().parents[1]
_DEFINITIONS: TypeAdapter[dict[str, dict[str, JsonValue]]] = TypeAdapter(
    dict[str, dict[str, JsonValue]]
)
PAGES = {
    Path("docs/using/spec-reference.md"): "spec",
    Path("docs/using/cli-reference.md"): "cli",
}
_SPEC_INTRO = """\
<!-- Generated by scripts/reference.py from the spec's JSON Schema; do not edit. -->

# Spec reference

Every field a spec can hold, from the JSON Schema specs are checked against
(`datadouble schema` prints it). A spec is YAML or JSON; fields not listed are
refused. Adapter settings, such as a source's `connection` or a store's, are
checked by the adapter named, and its README lists them.
"""
_CLI_INTRO = """\
<!-- Generated by scripts/reference.py from the command-line parser; do not edit. -->

# CLI reference

Every `datadouble` command and option. Each command builds a JSON request;
`--dry-run` prints it instead of running it, and `datadouble api` reads one
from standard input, so everything here is also available as JSON.
"""


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def type_of(schema: Mapping[str, JsonValue]) -> str:
    """A field's type in a few words, with links to the sections of objects."""
    reference = schema.get("$ref")
    if isinstance(reference, str):
        name = reference.rsplit("/", 1)[-1]
        return "JSON" if name == "JsonValue" else f"[{name}](#{name.lower()})"
    choices = schema.get("anyOf") or schema.get("oneOf")
    if isinstance(choices, list):
        kinds = [type_of(c) for c in choices if isinstance(c, dict) and c.get("type") != "null"]
        return " or ".join(dict.fromkeys(kinds))
    enum = schema.get("enum")
    if isinstance(enum, list):
        return " or ".join(f"`{value}`" for value in enum)
    kind = schema.get("type")
    items = schema.get("items")
    if kind == "array" and isinstance(items, dict):
        return f"list of {type_of(items)}"
    values = schema.get("additionalProperties")
    if kind == "object" and isinstance(values, dict):
        return f"map of {type_of(values)}"
    return str(kind or "any")


def default_of(schema: Mapping[str, JsonValue]) -> str:
    """A field's default as JSON, if it is worth showing."""
    if "default" not in schema:
        return ""
    default = schema["default"]
    if default in (None, [], {}):
        return ""
    return f"`{json.dumps(default)}`" if not isinstance(default, (dict, list)) else "see type"


def section(name: str, schema: Mapping[str, JsonValue], level: str) -> Iterator[str]:
    """One object's heading, description and table of fields."""
    yield f"{level} {name}\n"
    description = schema.get("description")
    if isinstance(description, str):
        yield f"{' '.join(description.replace('``', '`').split())}\n"
    properties = schema.get("properties")
    required = schema.get("required")
    needed = set(required) if isinstance(required, list) else set[JsonValue]()
    if isinstance(properties, dict) and properties:
        yield "| Field | Type | Default | Description |"
        yield "|---|---|---|---|"
        for field, value in properties.items():
            if not isinstance(value, dict):
                continue
            label = f"`{field}`" + (" (required)" if field in needed else "")
            text = value.get("description")
            words = _cell(str(text).replace("``", "`")) if isinstance(text, str) else ""
            yield f"| {label} | {_cell(type_of(value))} | {default_of(value)} | {words} |"
        yield ""
    elif "enum" in schema:
        yield f"One of {type_of(schema)}.\n"


def spec_page() -> str:
    """The spec reference, the top level first and then each definition by name."""
    schema = spec_schema()
    definitions = _DEFINITIONS.validate_python(schema.get("$defs", {}))
    lines = [_SPEC_INTRO, *section("The spec", schema, "##")]
    for name in sorted(definitions):
        if name != "JsonValue":
            lines.extend(section(name, definitions[name], "###"))
    return "\n".join(lines).rstrip() + "\n"


def _arguments(parser: CommandParser) -> Iterator[str]:
    rows: list[str] = []
    for action in parser.arguments:
        if action.dest == "help" or action.dest in {"command", "ci_command"}:
            continue
        if action.option_strings:
            name = ", ".join(f"`{flag}`" for flag in action.option_strings)
            if action.nargs != 0:
                name += f" `{action.metavar or action.dest.upper()}`"
        else:
            name = f"`{action.metavar or action.dest.upper()}`"
        help_text = action.help or ""
        if action.choices is not None:
            help_text += f" (one of {', '.join(str(c) for c in action.choices)})"
        if action.required:
            help_text += " (required)"
        rows.append(f"| {name} | {_cell(help_text)} |")
    if rows:
        yield "| Argument | Description |"
        yield "|---|---|"
        yield from rows
        yield ""


def _command(path: str, parser: CommandParser) -> Iterator[str]:
    yield f"## `datadouble {path}`\n"
    summary = parser.description or ""
    yield f"{summary[:1].upper()}{summary[1:]}.\n"
    yield from _arguments(parser)
    for name, child in parser.commands.items():
        yield from _command(f"{path} {name}", child)


def cli_page() -> str:
    """The CLI reference: global options, then every command in the parser's order."""
    parser = build_parser()
    lines = [_CLI_INTRO, "## Global options\n", *_arguments(parser)]
    for name, child in parser.commands.items():
        lines.extend(_command(name, child))
    return "\n".join(lines).rstrip() + "\n"


def pages() -> dict[Path, str]:
    """Every generated page, by path from the repository root."""
    builders = {"spec": spec_page, "cli": cli_page}
    return {path: builders[kind]() for path, kind in PAGES.items()}


def main(argv: Sequence[str] | None = None, root: Path = ROOT) -> int:
    """``write`` or ``check``."""
    arguments = list(sys.argv[1:] if argv is None else argv)
    if arguments == ["write"]:
        for path, text in pages().items():
            (root / path).parent.mkdir(parents=True, exist_ok=True)
            (root / path).write_text(text, encoding="utf-8")
        return 0
    if arguments == ["check"]:
        stale = [
            path
            for path, text in pages().items()
            if not (root / path).exists() or (root / path).read_text(encoding="utf-8") != text
        ]
        for path in stale:
            sys.stdout.write(f"{path} differs from what scripts/reference.py writes\n")
        return 1 if stale else 0
    sys.stderr.write(__doc__ or "")
    return 2


if __name__ == "__main__":
    sys.exit(main())

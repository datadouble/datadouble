"""The MongoDB engine adapter for Datadouble.

Spec settings::

    source:
      engine: mongodb
      connection:
        uri: {env: CINEMA_URI}   # mongodb:// or mongodb+srv://, by reference
        database: cinema
        sample: 1000             # documents sampled per collection for its fields

The source must be a replica set or sharded cluster: snapshot reads need one.
Extract reads through the driver. Working databases, restores, ``mongodump``
and ``mongorestore`` run in the official MongoDB image of the source's exact
version (``mongo:<version>``), or in ``source.image``, through the spec's
container runtime.
"""

from collections.abc import Generator, Mapping
from contextlib import contextmanager
from pathlib import Path

from pydantic import BaseModel, ConfigDict, Field, JsonValue
from pymongo import MongoClient
from pymongo.errors import PyMongoError

from datadouble.engine import ServerPlan, SourceSession, Tooling, WorkingDatabases
from datadouble.names import EngineName
from datadouble.planner import Capabilities
from datadouble.secrets import resolve_secret
from datadouble.settings import NoSettings, parse_settings
from datadouble.spec import ImageFormat, SecretRef
from datadouble_mongodb.server import Tools, default_image, upsert_user
from datadouble_mongodb.source import ENGINE, Client, MongoSource, failure
from datadouble_mongodb.working import DatabaseInfo, MongoWorking

MOUNT = "/var/lib/datadouble"
"""Where container servers mount a copy."""


class MongoConnection(BaseModel):
    """The ``source.connection`` settings."""

    model_config = ConfigDict(strict=True, frozen=True, extra="forbid")

    uri: SecretRef
    database: str = Field(min_length=1)
    sample: int = Field(default=1000, ge=1)


class MongoEngine:
    """Implements :class:`datadouble.engine.EngineAdapter` for MongoDB."""

    @property
    def name(self) -> EngineName:
        """``mongodb``."""
        return ENGINE

    @property
    def owner(self) -> str:
        """``999:999``, the user the official MongoDB image serves as."""
        return "999:999"

    def capabilities(self) -> Capabilities:
        """Both formats and aggregation expressions; no nested strategy or hooks."""
        return Capabilities(
            formats=(ImageFormat.PHYSICAL, ImageFormat.LOGICAL),
            expressions=True,
            nested=False,
            hooks=False,
        )

    @contextmanager
    def connect(self, connection: Mapping[str, JsonValue]) -> Generator[SourceSession]:
        """Connect to the source."""
        settings = parse_settings(MongoConnection, connection, "mongodb connection")
        client: Client = MongoClient(resolve_secret(settings.uri), serverSelectionTimeoutMS=10000)
        try:
            client.admin.command("ping")
        except PyMongoError as error:
            client.close()
            raise failure(error, "connecting to the source") from None
        with client:
            yield MongoSource(client, settings.database, settings.sample)

    def working(self, scratch: Path, tooling: Tooling, source_version: str) -> WorkingDatabases:
        """``mongod`` servers under ``scratch``, in the image for the source's version."""
        parse_settings(NoSettings, tooling.server, "mongodb server")
        image = tooling.image or default_image(source_version)
        return MongoWorking(Tools(tooling.runtime, image), scratch)

    def server(self, image: Path, server_image: str | None) -> ServerPlan:
        """The official MongoDB image of the image's version, on the copy.

        At start the user ``datadouble`` is created on the copy, or its
        password reset, to the copy's password, and the server then runs with
        authentication.
        """
        info = DatabaseInfo.model_validate_json((image / "database.json").read_bytes())
        data = f"{MOUNT}/db"
        # The password is generated by the replicate adapter (hex), so quoting it is safe.
        create = upsert_user("datadouble")
        start = (
            f"mongod --dbpath {data} --bind_ip 127.0.0.1 --fork --logpath /tmp/setup.log"
            f' && mongosh --quiet --eval "{create}" > /dev/null'
            f" && mongod --dbpath {data} --shutdown > /dev/null"
            f" && exec mongod --dbpath {data} --auth --bind_ip_all"
        )
        return ServerPlan(
            image=server_image or default_image(info.server_version),
            mount=MOUNT,
            owner=self.owner,
            command=("sh", "-c", start),
            ready=("mongosh", "--quiet", "--eval", "db.adminCommand('ping')"),
            port=27017,
            database=info.database,
            user="datadouble",
        )


def engine() -> MongoEngine:
    """The entry point named in ``datadouble.engines``."""
    return MongoEngine()
